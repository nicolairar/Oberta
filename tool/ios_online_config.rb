#!/usr/bin/env ruby
# Copies what iOS needs from config/supabase.json into ios/Flutter/Online.xcconfig
# (gitignored): today the reversed Google iOS client id, which Info.plist uses
# as the URL scheme Google Sign-In returns to.
#
#   ruby tool/ios_online_config.rb
#
# fastlane runs it before every build; run it by hand once before
# `flutter run` if you want Google sign-in on a local build.
require "json"

root = File.expand_path("..", __dir__)
config_path = File.join(root, "config", "supabase.json")
xcconfig_path = File.join(root, "ios", "Flutter", "Online.xcconfig")

client_id = File.exist?(config_path) ? JSON.parse(File.read(config_path))["GOOGLE_IOS_CLIENT_ID"].to_s.strip : ""

if client_id.empty?
  File.delete(xcconfig_path) if File.exist?(xcconfig_path)
  puts "No GOOGLE_IOS_CLIENT_ID: Google sign-in stays off"
  exit 0
end

suffix = ".apps.googleusercontent.com"
abort "GOOGLE_IOS_CLIENT_ID must end with #{suffix}" unless client_id.end_with?(suffix)
reversed = "com.googleusercontent.apps.#{client_id.delete_suffix(suffix)}"

File.write(xcconfig_path, <<~XCCONFIG)
  // Generated by tool/ios_online_config.rb from config/supabase.json. Do not commit.
  GOOGLE_REVERSED_CLIENT_ID = #{reversed}
XCCONFIG
puts "Wrote #{xcconfig_path}"
