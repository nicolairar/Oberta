// Writes lib/ui/screens/shop/shop_focus.dart: for every piece of the
// Cappello and Volto departments, the square of the bust its shop thumbnail
// zooms on, measured on the pixels of the piece on three players (a short
// crop, a huge afro, long hair), so the whole piece sits inside the round
// thumbnail with a little of the face around it.
//
//   flutter test tool/audit/thumb_focus_gen_test.dart
//
// test/ui/shop_thumb_fit_test.dart checks the table against the pixels.
import 'dart:io';
import 'dart:math';
import 'dart:ui';

import 'package:flutter_test/flutter_test.dart';
import 'package:oberta/online/shop_models.dart';
import 'package:oberta/ui/avatar/avatar_look.dart';

import '../../test/ui/thumb_measure.dart';

void main() {
  test('write the thumbnail focus table', () async {
    final lines = <String>[];
    for (final item in initialShopCatalog) {
      if (!focusSlots.contains(item.slot) || item.lookId == 'none') continue;
      final slot = LookSlot.values.byName(item.slot);
      Rect? box;
      final pixels = <Offset>[];
      for (final base in measureBases) {
        final worn = base.wearing(slot, item.lookId);
        if (worn == null) continue;
        final found = await piecePixels(base, worn, slot);
        pixels.addAll(found);
      }
      if (pixels.isEmpty) continue;
      for (final p in pixels) {
        box = box == null ? Rect.fromLTRB(p.dx, p.dy, p.dx, p.dy) : box.expandToInclude(Rect.fromLTRB(p.dx, p.dy, p.dx, p.dy));
      }
      final focus = focusAround(box!, pixels, item.slot);
      String f(double v) => v.toStringAsFixed(3);
      lines.add("  '${item.id}': Rect.fromLTWH(${f(focus.left)}, ${f(focus.top)}, ${f(focus.width)}, ${f(focus.height)}),");
    }
    File('lib/ui/screens/shop/shop_focus.dart').writeAsStringSync('''
// Generated by tool/audit/thumb_focus_gen_test.dart: do not edit by hand.
import 'dart:ui';

/// The square of the bust (in bust units) that the shop thumbnail of each
/// head and face piece zooms on: the whole piece inside the round
/// thumbnail, measured on its pixels. Pieces not here use their slot's zoom.
const pieceFocus = <String, Rect>{
${lines.join('\n')}
};
''');
    expect(lines, isNotEmpty);
    // ignore: avoid_print
    print('${lines.length} pieces, max side ${lines.map((l) => double.parse(RegExp(r', ([0-9.]+), [0-9.]+\)').firstMatch(l)!.group(1)!)).reduce(max)}');
  });
}
