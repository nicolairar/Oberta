#!/bin/sh
# Compila il motore della partita online in JavaScript per la Edge Function
# `game`. Da rifare (e committare) ogni volta che cambiano le regole, i bot
# o il passo del server: un test fallisce finché il bundle è vecchio.
set -e
cd "$(dirname "$0")/../.."
OUT=supabase/functions/game/engine.js
TMP=build/edge
mkdir -p "$TMP"
dart compile js -O2 --no-source-maps -o "$TMP/engine.js" tool/edge/engine_main.dart
SOURCES=$(dart run tool/edge/engine_sources.dart)
{
  echo "// GENERATED by tool/edge/build.sh from the Dart engine - do not edit. sources: $SOURCES"
  cat "$TMP/engine.js"
} > "$OUT"
echo "Motore scritto in $OUT ($(wc -c < "$OUT" | tr -d ' ') byte)"
